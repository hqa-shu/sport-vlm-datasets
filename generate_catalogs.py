#!/usr/bin/env python3
"""Generate bilingual catalogs and an offline HTML explorer from checked metadata."""
import argparse
import html
import json
from pathlib import Path
from catalog import validate_catalog

ROOT = Path(__file__).resolve().parent


def cell(value):
    return str(value).replace('|', '&#124;').replace('\n', ' ').replace('<', '&lt;').replace('>', '&gt;')


def render_markdown(data, chinese=False):
    title = '体育视觉语言资源目录' if chinese else 'Sports vision-language resource catalog'
    lines = ['# ' + title, '', '<!-- Generated by generate_catalogs.py; edit data/datasets.json instead. -->', '', '[Project overview](README.md) · [English](CATALOG.md) · [中文](README.zh-CN.md) · [Preparation guide](PREPARATION.md) · [Field definitions](SCHEMA.md)', '', '**%s resources · %s main + %s candidates · Revision %s**' % (data['total_entries'], data['main_entries'], data['additional_candidates'], data['catalog_revision_date']), '', '字段证据不等于全条目验证。空任务/模态与 unknown 表示尚未核查。public 仅指来源页面展示公开入口；未测试下载。' if chinese else 'Evidence applies to named fields, not the entire record. Empty tasks/modalities and unknown mean unchecked. Public means the source page lists a public entry point; downloads have not been tested.', '', '原 S/A/B/C 分组仅作历史准备成本信息保留，不作质量评分。许可证、媒体、标注与评估划分需分别确认。' if chinese else 'Inherited S/A/B/C groups remain historical preparation-cost notes, not quality scores. Check media, annotations, license and evaluation splits separately.', '', '| ID | Resource | Sport | Type | Tasks | Access | Language |', '|---:|---|---|---|---|---|---|']
    for e in data['datasets']:
        name = 'ShuttleSet family' if e['name'] == 'ShuttleSet系列' and not chinese else e['name']
        lines.append('| %s | [%s](#resource-%s) | %s | %s | %s | %s | %s |' % (e['id'], cell(name), e['id'], cell(e['sport'] if chinese else e['sport_en']), e['resource_type'], ', '.join(e['tasks']) or 'unknown', e['access_status'], e['language_status']))
    lines += ['', '## 条目详情与来源证据' if chinese else '## Resource details and evidence', '']
    for e in data['datasets']:
        lines += ['<a id="resource-%s"></a>' % e['id'], '', '### %s. %s' % (e['id'], cell(e['name'])), '', '**%s** · %s · %s' % (cell(e['name']), cell(e['sport_en']), e['resource_type']), '', '- **Tasks / modalities:** %s / %s' % (', '.join(e['tasks']) or 'unknown', ', '.join(e['modalities']) or 'unknown'), '- **Scale:** ' + cell(e['scale_note']), '- **Access:** ' + cell(e['access_note']), '- **License:** %s — %s' % (e['license']['name'] or e['license']['status'], cell(e['license']['note'])), '- **Official splits:** ' + cell(e['official_splits']), '- **Preparation:** ' + cell(e['preparation_note']), '- **Review:** %s (%s); download tested: %s' % (e['source_review'], e['source_review_date'] or 'unknown', str(e['download_tested']).lower()), '- **Primary sources:** ' + (' · '.join('[Source %s](%s)' % (i, u) for i,u in enumerate(e['paper_or_source_urls'],1)) or 'unknown'), '- **Access entry points:** ' + (' · '.join('[Access %s](%s)' % (i,u) for i,u in enumerate(e['access_urls'],1)) or 'unknown'), '']
        if e['evidence']:
            for item in e['evidence']:
                lines += ['> [%s · page read](%s): %s Fields: %s.' % (item['checked_on'], item['url'], cell(item['summary']), ', '.join(item['fields'])), '']
        else:
            lines += ['> No field-level evidence in this revision. Earlier source checks may establish paper identity only.', '']
        lines += ['<details><summary>Historical curation notes / 历史整理（未复核）</summary>', '', '- Original preparation group: ' + (e['tier_from_original_curation'] or 'candidate'), '- Historical scale: ' + cell(e['legacy_scale_note']), '- Historical access: ' + cell(e['legacy_access_note']), '', '</details>', '']
    return '\n'.join(lines)


def outputs(data):
    template = (ROOT / 'explorer-template.html').read_text(encoding='utf-8')
    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c').replace('&', '\\u0026').replace('>', '\\u003e')
    return {'CATALOG.md': render_markdown(data), 'README.zh-CN.md': render_markdown(data, True), 'index.html': template.replace('__CATALOG_JSON__', payload)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='exit nonzero if checked-in outputs are stale')
    args = parser.parse_args(argv)
    try:
        data = json.loads((ROOT / 'data/datasets.json').read_text(encoding='utf-8'))
        errors = validate_catalog(data)
        if errors: parser.exit(2, 'Invalid catalog: ' + '; '.join(errors) + '\n')
        generated = outputs(data)
    except (OSError, ValueError) as exc:
        parser.exit(2, 'Cannot generate: ' + str(exc) + '\n')
    stale = []
    for name, content in generated.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content: stale.append(name)
        else: path.write_text(content, encoding='utf-8')
    if stale: parser.exit(1, 'Stale generated files: ' + ', '.join(stale) + '\nRun python3 generate_catalogs.py\n')
    print('Generated files are current.' if args.check else 'Generated CATALOG.md, README.zh-CN.md and index.html.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
