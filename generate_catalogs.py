#!/usr/bin/env python3
"""Generate bilingual catalogs and an offline HTML explorer from checked metadata."""
import argparse
import html
import json
from pathlib import Path
from catalog import validate_catalog

ROOT = Path(__file__).resolve().parent


def cell(value):
    return str(value).replace('|', '&#124;').replace('\n', ' ').replace('<', '&lt;').replace('>', '&gt;')


def render_markdown(data, chinese=False):
    title = '体育视觉语言资源目录' if chinese else 'Sports vision-language resource catalog'
    nav = '[项目概览](README.md) · [English](CATALOG.md) · [中文](README.zh-CN.md) · [准备指南](PREPARATION.md) · [字段定义](SCHEMA.md)' if chinese else '[Project overview](README.md) · [English](CATALOG.md) · [中文](README.zh-CN.md) · [Preparation guide](PREPARATION.md) · [Field definitions](SCHEMA.md)'
    count = ('**%s 项资源 · %s 主目录 + %s 候选 · 更新 %s**' if chinese else '**%s resources · %s main + %s candidates · Revision %s**') % (data['total_entries'], data['main_entries'], data['additional_candidates'], data['catalog_revision_date'])
    lines = ['# ' + title, '', '<!-- Generated by generate_catalogs.py; edit data/datasets.json instead. -->', '', nav, '', count, '', '字段证据不等于全条目验证。空任务/模态与 unknown 表示尚未核查。public 仅指来源页面展示公开入口；未测试下载。' if chinese else 'Evidence applies to named fields, not the entire record. Empty tasks/modalities and unknown mean unchecked. Public means the source page lists a public entry point; downloads have not been tested.', '', '原 S/A/B/C 分组仅作历史准备成本信息保留，不作质量评分。许可证、媒体、标注与评估划分需分别确认。' if chinese else 'Inherited S/A/B/C groups remain historical preparation-cost notes, not quality scores. Check media, annotations, license and evaluation splits separately.', '', '| ID | 资源 | 运动 | 类型 | 任务 | 访问 | 语言监督 |' if chinese else '| ID | Resource | Sport | Type | Tasks | Access | Language |', '|---:|---|---|---|---|---|---|']
    for e in data['datasets']:
        name = 'ShuttleSet family' if e['name'] == 'ShuttleSet系列' and not chinese else e['name']
        lines.append('| %s | [%s](#resource-%s) | %s | %s | %s | %s | %s |' % (e['id'], cell(name), e['id'], cell(e['sport'] if chinese else e['sport_en']), e['resource_type'], ', '.join(e['tasks']) or 'unknown', e['access_status'], e['language_status']))
    lines += ['', '## 条目详情与来源证据' if chinese else '## Resource details and evidence', '']
    for e in data['datasets']:
        notes = e.get('notes_zh', {}) if chinese else e
        labels = ['任务 / 模态', '规模', '访问说明', '许可', '官方划分', '准备建议', '核查状态', '原始来源', '访问入口'] if chinese else ['Tasks / modalities', 'Scale', 'Access', 'License', 'Official splits', 'Preparation', 'Review', 'Primary sources', 'Access entry points']
        values = [
            '%s / %s' % (', '.join(e['tasks']) or 'unknown', ', '.join(e['modalities']) or 'unknown'),
            cell(notes.get('scale_note', e['scale_note'])),
            cell(notes.get('access_note', e['access_note'])),
            '%s — %s' % (e['license']['name'] or e['license']['status'], cell(notes.get('license_note', e['license']['note']))),
            cell(notes.get('official_splits', e['official_splits'])),
            cell(notes.get('preparation_note', e['preparation_note'])),
            '%s (%s); %s: %s' % (e['source_review'], e['source_review_date'] or 'unknown', '下载测试' if chinese else 'download tested', str(e['download_tested']).lower()),
            ' · '.join('[%s %s](%s)' % ('来源' if chinese else 'Source', i, u) for i,u in enumerate(e['paper_or_source_urls'],1)) or 'unknown',
            ' · '.join('[%s %s](%s)' % ('入口' if chinese else 'Access', i, u) for i,u in enumerate(e['access_urls'],1)) or 'unknown'
        ]
        lines += ['<a id="resource-%s"></a>' % e['id'], '', '### %s. %s' % (e['id'], cell(e['name'])), '', '**%s** · %s · %s' % (cell(e['name']), cell(e['sport'] if chinese else e['sport_en']), e['resource_type']), '']
        lines += ['- **%s:** %s' % pair for pair in zip(labels, values)]
        lines.append('')
        if e['evidence']:
            for item in e['evidence']:
                lines += ['> [%s · %s](%s): %s %s: %s.' % (item['checked_on'], '网页核查' if chinese else 'page read', item['url'], cell(item['summary']), '适用字段' if chinese else 'Fields', ', '.join(item['fields'])), '']
        else:
            lines += ['> 本次修订未添加字段级证据。此前核查可能仅确认论文身份。' if chinese else '> No field-level evidence in this revision. Earlier source checks may establish paper identity only.', '']
        lines += ['<details><summary>Historical curation notes / 历史整理（未复核）</summary>', '', '- %s: %s' % ('原准备成本分组' if chinese else 'Original preparation group', e['tier_from_original_curation'] or 'candidate'), '- %s: %s' % ('历史规模' if chinese else 'Historical scale', cell(e['legacy_scale_note'])), '- %s: %s' % ('历史访问说明' if chinese else 'Historical access', cell(e['legacy_access_note'])), '', '</details>', '']
    return '\n'.join(lines)


def outputs(data):
    template = (ROOT / 'explorer-template.html').read_text(encoding='utf-8')
    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c').replace('&', '\\u0026').replace('>', '\\u003e')
    return {'CATALOG.md': render_markdown(data), 'README.zh-CN.md': render_markdown(data, True), 'index.html': template.replace('__CATALOG_JSON__', payload)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='exit nonzero if checked-in outputs are stale')
    args = parser.parse_args(argv)
    try:
        data = json.loads((ROOT / 'data/datasets.json').read_text(encoding='utf-8'))
        errors = validate_catalog(data)
        if errors: parser.exit(2, 'Invalid catalog: ' + '; '.join(errors) + '\n')
        generated = outputs(data)
    except (OSError, ValueError) as exc:
        parser.exit(2, 'Cannot generate: ' + str(exc) + '\n')
    stale = []
    for name, content in generated.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content: stale.append(name)
        else: path.write_text(content, encoding='utf-8')
    if stale: parser.exit(1, 'Stale generated files: ' + ', '.join(stale) + '\nRun python3 generate_catalogs.py\n')
    print('Generated files are current.' if args.check else 'Generated CATALOG.md, README.zh-CN.md and index.html.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
